"""Render a standalone LaTeX checklist for one chapter: read, practise on Duolingo, work the book-only topics, finish."""

from __future__ import annotations

from .catalog import Chapter, Duolingo, Textbook, _ordinal
from .lanes import chapter_lanes, section_lanes
from .mapping import Mapping

RATING_LABEL = {"full": "full", "partial": "partial", "prerequisite": "prereq"}

_TEX_SPECIAL = {
  "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
  "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
}


def tex(text: str) -> str:
  """Escape plain text for LaTeX."""
  return "".join(_TEX_SPECIAL.get(c, c) for c in str(text))


PREAMBLE = r"""\documentclass[11pt]{article}
% Generated by scripts/build_checklists.py from the data files in data/. Do not edit by hand.
\pdfinfoomitdate=1
\pdftrailerid{}
\pdfsuppressptexinfo=-1
\usepackage[letterpaper,margin=0.8in]{geometry}
\usepackage[T1]{fontenc}
\usepackage{lmodern}
\usepackage{amssymb}
\usepackage{enumitem}
\usepackage[most]{tcolorbox}
\usepackage{xcolor}
\usepackage{titlesec}
\usepackage[hidelinks,pdfcreator={precalc-tutor},pdfproducer={pdflatex}]{hyperref}

\definecolor{accent}{HTML}{1F3A5F}
\definecolor{soft}{HTML}{EEF3FA}
\definecolor{warn}{HTML}{FFF4E5}
\pagestyle{plain}
\setlength{\parindent}{0pt}
\setlength{\parskip}{4pt}
\raggedright

\titleformat{\section}{\large\bfseries\color{accent}}{}{0pt}{}
\titlespacing*{\section}{0pt}{14pt}{4pt}
\titleformat{\subsection}{\normalsize\bfseries\color{accent}}{}{0pt}{}
\titlespacing*{\subsection}{0pt}{10pt}{2pt}

\newlist{checks}{itemize}{1}
\setlist[checks]{label=$\square$,leftmargin=2em,itemsep=2pt,topsep=2pt}
\newcommand{\aside}[1]{{\small\itshape #1}}
\newcommand{\tagright}[1]{\hfill{\small\color{gray}#1}}
\newtcolorbox{infobox}{colback=soft,colframe=accent,boxrule=0.6pt,arc=2pt,left=6pt,right=6pt,top=4pt,bottom=4pt}
\newtcolorbox{draftbox}{colback=warn,colframe=orange!70!black,boxrule=0.5pt,arc=2pt,left=6pt,right=6pt,top=3pt,bottom=3pt}
"""


def _label(ch: Chapter) -> str:
  return f"{'Appendix' if ch.is_appendix else 'Chapter'} {ch.id}"


def render_chapter(book: Textbook, course: Duolingo, mapping: Mapping, chapter_id: str) -> str:
  ch = next(c for c in book.chapters if c.id == chapter_id)
  label = _label(ch)
  lines: list[str] = [PREAMBLE, r"\hypersetup{pdftitle={" + tex(f"{label} checklist: {ch.title}") + "}}", r"\begin{document}", ""]

  lines += [
    r"{\LARGE\bfseries\color{accent} " + tex(f"{label} Checklist") + r"}\par",
    r"\vspace{2pt}",
    r"{\large " + tex(ch.title) + r"}\par",
    r"\vspace{2pt}",
    r"{\small " + tex(f"{book.author}, ") + r"\emph{" + tex(book.title) + "}"
    + tex(f", {_ordinal(book.edition)} ed., p. {ch.page}. Tick each box as you go.") + r"}\par",
    r"\vspace{6pt}",
    r"\begin{infobox}",
    "Work through the four parts in order: read each section, practise the matching Duolingo units, work the "
    "book-only topics that Duolingo does not cover, then finish the chapter. Duolingo units are grouped by lane "
    "(a grade or a topic in the app) and listed in the order the app shows them, so you can follow one lane from "
    r"top to bottom. \textbf{full} = the unit practises the section's main skill, \textbf{partial} = part of it, "
    r"\textbf{prereq} = a warm-up from an earlier grade.",
    r"\end{infobox}",
  ]
  summary = mapping.chapter_summaries.get(ch.id, "")
  if summary:
    lines += [r"\textbf{In this chapter:} " + tex(summary), ""]
  drafts = [s.id for s in ch.sections if not (mapping.entry(s.id) and mapping.entry(s.id).reviewed)]
  if drafts:
    lines += [r"\begin{draftbox}", r"\textbf{Draft.} " + tex(
      f"The Duolingo mapping for {'this chapter' if len(drafts) == len(ch.sections) else 'sections ' + ', '.join(drafts)} "
      "has not been reviewed yet, so treat the unit choices as a first pass."), r"\end{draftbox}"]

  # 1. Read
  lines += ["", r"\section{1.\quad Read the textbook sections}", r"\begin{checks}"]
  for s in ch.sections:
    lines.append(r"  \item " + tex(f"{s.id} {s.title}") + r"\tagright{" + tex(f"p. {s.page}") + "}")
  lines += [r"\end{checks}"]

  # 2. Practise on Duolingo, by lane
  rows = chapter_lanes(ch, mapping, course)
  lines += ["", r"\section{2.\quad Practise on Duolingo}"]
  if rows:
    lines.append("Pick one lane and work down it; the grade lanes go deepest. The note after each unit gives its rating "
                 "and the textbook sections it serves.")
    for row in rows:
      lines += [r"\subsection{" + tex(row.lane.name) + "}", r"\begin{checks}"]
      for lu in row.units:
        lines.append(r"  \item " + tex(lu.unit.name) + r"\quad\aside{" + tex(f"{RATING_LABEL[lu.rating]}, {', '.join(lu.sections)}")
                     + r"}\tagright{unit " + tex(str(lu.unit.order)) + "}")
      lines.append(r"\end{checks}")
  else:
    lines.append("No Duolingo unit covers this chapter. Use the book for every section.")

  # 3. Section by section
  lines += ["", r"\section{3.\quad Section by section}",
            "For each section: what Duolingo covers (the units are ticked off in part 2) and the book-only topics to work "
            "in the textbook. Tick each book-only topic once you have worked examples of it."]
  for s in ch.sections:
    e = mapping.entry(s.id)
    lines += [r"\subsection{" + tex(f"{s.id} {s.title}") + r"\tagright{" + tex(f"p. {s.page}") + "}}"]
    if e and e.note:
      lines.append(tex(e.note) + r"\par")
    srows = section_lanes(e, course) if e else []
    if srows:
      parts = []
      for row in srows:
        parts.append(r"\textbf{" + tex(row.lane.name) + ":} " + "; ".join(
          tex(f"{lu.unit.order}. {lu.unit.name} ({RATING_LABEL[lu.rating]})") for lu in row.units))
      lines.append(r"{\small \textit{Duolingo:} " + r"\\ ".join(parts) + r"}\par")
    else:
      lines.append(r"{\small \textit{Duolingo:} no unit covers this section.}\par")
    if e and e.gaps:
      lines += [r"{\small\textit{Book only:}}", r"\begin{checks}"]
      lines += [r"  \item " + tex(g) for g in e.gaps]
      lines.append(r"\end{checks}")

  # 4. Finish the chapter
  if ch.end_matter:
    lines += ["", r"\section{4.\quad Finish the chapter}", r"\begin{checks}"]
    for title, page in ch.end_matter:
      lines.append(r"  \item " + tex(title) + r"\tagright{" + tex(f"p. {page}") + "}")
    lines.append(r"\end{checks}")

  lines += [
    "", r"\vfill",
    r"{\footnotesize\color{gray}",
    tex(f"Duolingo unit numbers are each unit's position in that grade's or topic's path in the Duolingo Math app, as "
        f"recorded on {course.last_verified} ({course.platform}); the app may reorder them. Textbook: {book.citation()} "
        "Only titles and unit names are reproduced, for reference; no textbook or Duolingo content is included. "
        "This checklist is licensed CC BY 4.0; see the repository NOTICE for third-party material.") + r"\par}",
    "", r"\end{document}", "",
  ]
  return "\n".join(lines)
